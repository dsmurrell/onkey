// Writes lib/catalogs.ts: an import for every translation in messages/ (<code>.json, not en.json or CREDITS.json),
// so a new language shows up in the window, and in Settings' language picker, by adding its file. Run before every
// build (npm's prebuild); the file is committed so tsc and the tests work without a build, and catalogs.test.mjs
// checks it's current.
//   node scripts/catalogs.mjs           (from ui/)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const UI = join(dirname(fileURLToPath(import.meta.url)), "..");
const CODE = /^([a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*)\.json$/;

/** The translations there are files for, sorted ("es", "es-ES", …; never "en"). */
export function translationCodes(dir = join(UI, "messages")) {
  return readdirSync(dir).map(f => CODE.exec(f)?.[1]).filter(c => c && c !== "en").sort();
}

/** lib/catalogs.ts's text for these codes. */
export function catalogsSource(codes) {
  const id = c => "m_" + c.replace(/-/g, "_");
  return [
    "// Generated by scripts/catalogs.mjs (run before every build): every translation in messages/. Don't edit.",
    'import type { Catalog } from "./i18n";',
    ...codes.map(c => `import ${id(c)} from "../messages/${c}.json" with { type: "json" };`),
    "",
    "/** The translations, by code (English, the source, is imported by i18n.ts itself). */",
    `export const TRANSLATIONS: Record<string, Catalog> = {${codes.length ? " " + codes.map(c => `${JSON.stringify(c)}: ${id(c)}`).join(", ") + " " : ""}};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = join(UI, "lib", "catalogs.ts");
  const text = catalogsSource(translationCodes());
  let was = "";
  try { was = readFileSync(file, "utf8"); } catch {}
  if (was !== text) { writeFileSync(file, text); console.log(`[ui] catalogs: ${translationCodes().join(", ") || "English only"}`); }
}
